#!/usr/bin/env bun
// Bundles omp-collab/extension.ts into omp-collab/omp-collab.js for the installed omp version.
// Only omp's collab/ sources (and @oh-my-pi/pi-wire, which omp does not expose to extensions) are
// bundled; every other @oh-my-pi import stays external so omp resolves it to its in-process modules.
// Rerun after upgrading omp: `npm run build:collab`.
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import * as path from "node:path";
import { $, type BunPlugin } from "bun";

const here = import.meta.dir;
const version = (await $`omp --version`.text()).trim().replace(/^omp\//, "");
const work = await mkdtemp(path.join(tmpdir(), "omp-collab-"));

try {
	const unpack = async (name: string, dir: string): Promise<string> => {
		const tarball = (await $`npm pack @oh-my-pi/${name}@${version} --pack-destination ${work} --silent`.text()).trim();
		const dest = path.join(work, dir);
		await mkdir(dest);
		await $`tar -xzf ${path.join(work, tarball)} -C ${dest} --strip-components=1`;
		return path.join(dest, "src");
	};
	const agentSrc = await unpack("pi-coding-agent", "coding-agent");
	const wireSrc = await unpack("pi-wire", "wire");
	const collabDir = path.join(agentSrc, "collab") + path.sep;

	// collab/settings.ts registers collab.* settings, which omp already did (register() throws on
	// duplicates): reuse omp's registered handles instead.
	const settingsSource = await Bun.file(path.join(collabDir, "settings.ts")).text();
	const settingIds = [...settingsSource.matchAll(/export const (\w+) = register\(\{\s*id: "([^"]+)"/g)];
	if (settingIds.length === 0) throw new Error("no settings found in collab/settings.ts");
	const settingsShim = [
		'import { lookup } from "@oh-my-pi/pi-coding-agent/config/registry";',
		"function hostSetting(id) {",
		"\tconst setting = lookup(id);",
		'\tif (!setting) throw new Error(`omp does not register setting ${id}`);',
		"\treturn setting;",
		"}",
		...settingIds.map(([, name, id]) => `export const ${name} = hostSetting(${JSON.stringify(id)});`),
	].join("\n");

	const hostPackage = /^@oh-my-pi\/(pi-agent-core|pi-ai|pi-catalog|pi-coding-agent|pi-natives|pi-tui|pi-utils)(\/.*)?$/;
	const ompModules: BunPlugin = {
		name: "omp-modules",
		setup(build) {
			build.onResolve({ filter: /^@oh-my-pi\/pi-coding-agent\/collab\// }, args => ({
				path: path.join(agentSrc, `${args.path.slice("@oh-my-pi/pi-coding-agent/".length)}.ts`),
			}));
			build.onResolve({ filter: /^@oh-my-pi\/pi-wire$/ }, () => ({ path: path.join(wireSrc, "index.ts") }));
			build.onResolve({ filter: hostPackage }, args => ({ path: args.path, external: true }));
			build.onResolve({ filter: /^\.\/settings$/ }, args =>
				args.importer.startsWith(collabDir) ? { path: "collab-settings", namespace: "omp-shim" } : undefined,
			);
			build.onLoad({ filter: /.*/, namespace: "omp-shim" }, () => ({ contents: settingsShim, loader: "js" }));
			// Bun keeps an external's original specifier, so rewrite collab/'s `../<path>` imports to the
			// bare `@oh-my-pi/pi-coding-agent/<path>` form omp serves to extensions before resolution.
			build.onLoad({ filter: /\/src\/collab\/[^/]+\.ts$/ }, async args => ({
				contents: (await Bun.file(args.path).text()).replaceAll('from "../', 'from "@oh-my-pi/pi-coding-agent/'),
				loader: "ts",
			}));
		},
	};

	const result = await Bun.build({
		entrypoints: [path.join(here, "extension.ts")],
		target: "bun",
		format: "esm",
		define: { OMP_COLLAB_BUILT_FOR: JSON.stringify(version) },
		plugins: [ompModules],
	});
	if (!result.success) throw new AggregateError(result.logs, "bundle failed");
	const code = await result.outputs[0].text();
	if (/from "\.\.?\//.test(code)) throw new Error("bundle still has relative imports omp cannot resolve");
	const header = `// Generated by omp-collab/build.ts from @oh-my-pi/pi-coding-agent@${version}. Do not edit.\n`;
	await Bun.write(path.join(here, "omp-collab.js"), header + code);
	console.log(`omp-collab/omp-collab.js built for omp ${version}`);
} finally {
	await rm(work, { recursive: true, force: true });
}
